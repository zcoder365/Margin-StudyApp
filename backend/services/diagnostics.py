STATUS_PRIORITY = {"needs_practice": 3.0, "insufficient_evidence": 2.0, "developing": 1.5, "demonstrated": 0.0}
PRACTICE_MINUTES = {"needs_practice": 45, "insufficient_evidence": 25, "developing": 30}


def practice_priorities(concept_mastery, concepts, upcoming, today):
    """rank concepts to practise.

    concept_mastery: {conceptId: mastery()}; upcoming: {conceptId: [assessment dicts with id, title, dueDate (date), weight]}
    score = status weight × deadline proximity (≤7 days ×2, ≤14 ×1.5, later ×1, none ×0.8) × (1 + weight/100)
    """
    items = []
    for c in concepts:
        m = concept_mastery.get(c["id"]) or {"status": "insufficient_evidence", "reasons": []}
        base = STATUS_PRIORITY.get(m["status"], 0)
        if base == 0:
            continue
        nxt = sorted([a for a in upcoming.get(c["id"], []) if a.get("dueDate") and a["dueDate"] >= today],
                     key=lambda a: a["dueDate"])
        a = nxt[0] if nxt else None
        if a:
            days = (a["dueDate"] - today).days
            prox = 2.0 if days <= 7 else 1.5 if days <= 14 else 1.0
            weight = 1 + (a.get("weight") or 0) / 100
        else:
            prox, weight = 0.8, 1.0
        reason = {"needs_practice": "needs practice", "insufficient_evidence": "not enough evidence yet",
                  "developing": "still developing"}[m["status"]]
        if a:
            reason += f"; {a['title']} is in {(a['dueDate'] - today).days} days"
        items.append({
            "conceptId": c["id"], "name": c["name"], "status": m["status"],
            "score": round(base * prox * weight, 2), "minutes": PRACTICE_MINUTES[m["status"]],
            "assessmentId": a["id"] if a else None, "assessmentTitle": a["title"] if a else None,
            "deadline": a["dueDate"].isoformat() if a else None, "reason": reason,
        })
    items.sort(key=lambda i: (-i["score"], i["name"]))
    return items


def allocate_practice(items, capacity, planned_load, last_day_for, max_per_day=2):
    """propose dates for practice sessions without overfilling days.

    capacity: {date: free minutes}; planned_load: {date: minutes already planned}
    last_day_for: {assessmentId: last date practice still helps}
    only uses time left over after existing plans; at most `max_per_day` practice sessions per day.
    """
    left = {d: max(capacity[d] - planned_load.get(d, 0), 0) for d in capacity}
    count = {d: 0 for d in capacity}
    proposed, unallocated = [], []
    for it in items:
        last = last_day_for.get(it.get("assessmentId")) or (max(capacity) if capacity else None)
        day = next((d for d in sorted(left) if (last is None or d <= last) and left[d] >= it["minutes"] and count[d] < max_per_day), None)
        if day is None:
            unallocated.append({**it, "why": "no free time left before the assessment"})
            continue
        left[day] -= it["minutes"]
        count[day] += 1
        proposed.append({**it, "date": day.isoformat()})
    return proposed, unallocated
