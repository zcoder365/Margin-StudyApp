QUESTION_TYPES = ("mcq", "numeric", "short")
CONFIDENCE_LEVELS = (1, 2, 3)  # guessing, somewhat sure, sure
SELF_GRADES = {"correct": 1.0, "partial": 0.5, "incorrect": 0.0}
FLAG_REASONS = ("incorrect", "ambiguous", "poorly_worded", "off_topic", "other")

MASTERY_RULES = {
    "insufficient_evidence": "Fewer than 3 answered questions, or answers to fewer than 2 different questions, about this concept.",
    "needs_practice": "Recent weighted accuracy under 60%, 2 of the last 3 answers wrong, or a confident wrong answer in the last 2.",
    "developing": "Enough evidence, but not yet consistently correct.",
    "demonstrated": "Recent weighted accuracy of at least 80%, the latest answer correct, at least 2 different questions answered correctly, and no confident mistakes in the last 3.",
}
EVIDENCE_NOTES = [
    "Recent answers count more (an answer loses half its weight every 3 weeks).",
    "Harder questions count a little more; self-graded answers count a little less.",
    "Questions you flagged as wrong or unclear are left out.",
    "Confidence is tracked to spot misconceptions, but feeling sure is never counted as knowing it.",
]

EXAM_CLAIM = re.compile(r"\b(will|is going to|guaranteed to)\s+(appear|be|show up)\s+on\s+(the|your)\s+(exam|test|midterm|final|quiz)", re.I)


# -----------------------------------------------------------------------------
# safe numeric evaluation
# -----------------------------------------------------------------------------
_FUNCS = {
    "sqrt": math.sqrt, "ln": math.log, "log": math.log10, "log10": math.log10, "log2": math.log2,
    "exp": math.exp, "sin": math.sin, "cos": math.cos, "tan": math.tan, "abs": abs,
}
_CONSTS = {"pi": math.pi, "e": math.e, "π": math.pi}


class NumericParseError(ValueError):
    pass


def safe_eval(expr):
    """evaluate a short arithmetic expression without eval(). raises NumericParseError."""
    if not isinstance(expr, (str, int, float)) or isinstance(expr, bool):
        raise NumericParseError("not a number")
    if isinstance(expr, (int, float)):
        return float(expr)
    s = expr.strip()
    if not s or len(s) > 120:
        raise NumericParseError("empty or too long")
    s = s.replace("×", "*").replace("÷", "/").replace("^", "**").replace("−", "-").replace("π", "pi")
    s = re.sub(r"(?<=\d),(?=\d{3}\b)", "", s)  # thousands separators
    if s.endswith("%"):
        s = f"({s[:-1]})/100"
    try:
        tree = ast.parse(s, mode="eval")
    except SyntaxError:
        raise NumericParseError("couldn't read that as a number")

    def ev(node):
        if isinstance(node, ast.Expression):
            return ev(node.body)
        if isinstance(node, ast.Constant) and isinstance(node.value, (int, float)) and not isinstance(node.value, bool):
            return float(node.value)
        if isinstance(node, ast.Name) and node.id in _CONSTS:
            return _CONSTS[node.id]
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)):
            v = ev(node.operand)
            return -v if isinstance(node.op, ast.USub) else v
        if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub, ast.Mult, ast.Div, ast.Pow, ast.Mod)):
            a, b = ev(node.left), ev(node.right)
            if isinstance(node.op, ast.Pow):
                if abs(b) > 64 or abs(a) > 1e6:
                    raise NumericParseError("number too large")
                return a ** b
            if isinstance(node.op, (ast.Div, ast.Mod)) and b == 0:
                raise NumericParseError("division by zero")
            if isinstance(node.op, ast.Add):
                return a + b
            if isinstance(node.op, ast.Sub):
                return a - b
            if isinstance(node.op, ast.Mult):
                return a * b
            if isinstance(node.op, ast.Div):
                return a / b
            return a % b
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in _FUNCS and len(node.args) == 1 and not node.keywords:
            try:
                return float(_FUNCS[node.func.id](ev(node.args[0])))
            except (ValueError, OverflowError):
                raise NumericParseError("math error")
        raise NumericParseError("only numbers, + − × ÷ ^ and sqrt/ln/log/sin/cos/tan/exp are allowed")

    try:
        value = ev(tree)
    except (OverflowError, TypeError):
        raise NumericParseError("number too large")
    if isinstance(value, complex) or math.isnan(value) or math.isinf(value):
        raise NumericParseError("not a real number")
    return value


def grade_numeric(response, answer, abs_tol=None, rel_tol=None):
    """→ (correct: bool, parsed: float). raises NumericParseError if the response can't be read."""
    got = safe_eval(response)
    want = float(answer)
    if abs_tol is None and rel_tol is None:
        rel_tol = 0.01
    ok = False
    if abs_tol is not None and abs(got - want) <= abs_tol + 1e-12:
        ok = True
    if rel_tol is not None and abs(got - want) <= rel_tol * max(abs(want), 1e-9) + 1e-12:
        ok = True
    return ok, got


