def _age_days(at, now):
    if isinstance(at, str):
        try:
            at = datetime.fromisoformat(at)
        except ValueError:
            return 0
    if at is None:
        return 0
    if at.tzinfo is None:
        at = at.replace(tzinfo=timezone.utc)
    return max((now - at).total_seconds() / 86400, 0)


def attempt_score(a):
    """1.0 / 0.5 / 0.0, or None if not yet graded."""
    if a.get("gradingMethod") == "self":
        return SELF_GRADES.get(a.get("selfGrade"))
    if a.get("correct") is None:
        return None
    return 1.0 if a["correct"] else 0.0


def mastery(attempts, now=None, excluded_questions=()):
    """attempts: one concept's attempts (any order). → {status, evidence, reasons}."""
    now = now or datetime.now(timezone.utc)
    usable = [a for a in attempts if a.get("questionId") not in excluded_questions and attempt_score(a) is not None]
    usable.sort(key=lambda a: _age_days(a.get("createdAt"), now), reverse=True)  # oldest first
    n = len(usable)
    distinct = {a["questionId"] for a in usable}
    distinct_correct = {a["questionId"] for a in usable if attempt_score(a) == 1.0}
    wsum = wtot = 0.0
    for a in usable:
        w = 0.5 ** (_age_days(a.get("createdAt"), now) / 21)
        w *= {1: 0.8, 2: 1.0, 3: 1.2}.get(a.get("difficulty"), 1.0)
        if a.get("gradingMethod") == "self":
            w *= 0.6
        wsum += w * attempt_score(a)
        wtot += w
    acc = wsum / wtot if wtot else None
    last3 = usable[-3:]
    confident_wrong = lambda a: a.get("confidence") == 3 and attempt_score(a) == 0.0  # noqa: E731
    evidence = {
        "attempts": n,
        "distinctQuestions": len(distinct),
        "weightedAccuracy": round(acc, 2) if acc is not None else None,
        "lastAttemptAt": usable[-1].get("createdAt") if usable else None,
        "lastCorrect": attempt_score(usable[-1]) == 1.0 if usable else None,
        "confidentErrors": sum(1 for a in usable if confident_wrong(a)),
        "unsureCorrect": sum(1 for a in usable if a.get("confidence") == 1 and attempt_score(a) == 1.0),
        "selfGraded": sum(1 for a in usable if a.get("gradingMethod") == "self"),
    }
    reasons = []
    if n < 3 or len(distinct) < 2:
        status = "insufficient_evidence"
        reasons.append(f"{n} answer{'s' if n != 1 else ''} to {len(distinct)} different question{'s' if len(distinct) != 1 else ''} so far")
    elif acc < 0.6 or sum(1 for a in last3 if attempt_score(a) == 0.0) >= 2 or any(confident_wrong(a) for a in usable[-2:]):
        status = "needs_practice"
        if acc < 0.6:
            reasons.append(f"recent accuracy {round(acc * 100)}%")
        if sum(1 for a in last3 if attempt_score(a) == 0.0) >= 2:
            reasons.append("2 of your last 3 answers were wrong")
        if any(confident_wrong(a) for a in usable[-2:]):
            reasons.append("you were sure of a recent wrong answer — possibly a misconception")
    elif acc >= 0.8 and attempt_score(usable[-1]) == 1.0 and len(distinct_correct) >= 2 and not any(confident_wrong(a) for a in last3):
        status = "demonstrated"
        reasons.append(f"recent accuracy {round(acc * 100)}% across {len(distinct)} different questions")
    else:
        status = "developing"
        reasons.append(f"recent accuracy {round(acc * 100)}%")
        if attempt_score(usable[-1]) != 1.0:
            reasons.append("your latest answer wasn't fully correct")
    if evidence["unsureCorrect"] and status != "insufficient_evidence":
        reasons.append(f"{evidence['unsureCorrect']} correct answer{'s were' if evidence['unsureCorrect'] != 1 else ' was'} a guess")
    return {"status": status, "evidence": evidence, "reasons": reasons}


def error_patterns(attempts, questions, concepts):
    """recurring problems worth naming: confident misses per concept, repeated misses, sticky distractors."""
    qmap = {q["id"]: q for q in questions}
    cmap = {c["id"]: c for c in concepts}
    patterns = []
    by_concept_conf = {}
    by_question_miss = {}
    distractors = {}
    for a in attempts:
        if attempt_score(a) != 0.0:
            continue
        for cid in a.get("conceptIds", []):
            if a.get("confidence") == 3:
                by_concept_conf[cid] = by_concept_conf.get(cid, 0) + 1
        by_question_miss[a["questionId"]] = by_question_miss.get(a["questionId"], 0) + 1
        q = qmap.get(a["questionId"])
        if q and q.get("type") == "mcq" and isinstance(a.get("response"), int):
            k = (a["questionId"], a["response"])
            distractors[k] = distractors.get(k, 0) + 1
    for cid, n in by_concept_conf.items():
        if n >= 2 and cid in cmap:
            patterns.append({"type": "confident_errors", "conceptId": cid,
                             "message": f"You were sure, but wrong, {n} times on “{cmap[cid]['name']}” — worth re-checking the underlying idea, not just the answers."})
    for qid, n in by_question_miss.items():
        if n >= 2 and qid in qmap:
            patterns.append({"type": "repeat_miss", "questionId": qid, "conceptId": (qmap[qid].get("conceptIds") or [None])[0],
                             "message": f"Missed the same question {n} times: “{qmap[qid]['prompt'][:80]}…”"})
    for (qid, choice), n in distractors.items():
        q = qmap[qid]
        if n >= 2 and choice < len(q.get("choices", [])):
            patterns.append({"type": "sticky_distractor", "questionId": qid, "conceptId": (q.get("conceptIds") or [None])[0],
                             "message": f"Chose “{q['choices'][choice][:60]}” {n} times for the same question."})
    return patterns


