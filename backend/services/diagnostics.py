def build_question_prompt(course_name, concepts, objectives, excerpts, count, avoid=None):
    concept_lines = "\n".join(f"[{c['id']}] {c['name']}: {c.get('description', '')}" for c in concepts)
    obj_lines = "\n".join(f"- {o['text']}" for o in objectives) or "(none)"
    exc = "\n".join(f"[D{e['docIndex']} p{e['page']}] {e['text']}" for e in excerpts) or "(no course material available)"
    avoid_lines = "\n".join(f"- {a}" for a in (avoid or [])[:30]) or "(none)"
    return f"""You write short diagnostic questions that reveal whether a university student can APPLY each concept.
Course: {course_name}. Write {count} questions spread across these concepts:
{concept_lines}

Rules:
- Ground questions in the course material excerpts where possible. When you do, copy a short verbatim "quote" and give its "docRef" and "page".
  If a question is your own example not taken from the material, set quote/docRef/page to null.
- Prefer application and worked problems over recall. Mix difficulties 1 (basic) to 3 (challenging).
- Types: "mcq" (3–5 plausible choices, exactly one correct), "numeric" (a single numeric answer; give "answer" as a number
  and an absolute "tolerance"), "short" (a few sentences; give a concise "modelAnswer" and 2–4 "keyPoints").
  Use "numeric" for calculations so answers can be checked exactly.
- Every question needs an "explanation" of the correct answer.
- Never claim a question will appear on an exam.
- Don't repeat these existing questions:
{avoid_lines}

Respond with ONLY JSON:
{{"questions": [{{"type": "mcq"|"numeric"|"short", "conceptIds": [concept ids from the list], "prompt": string,
  "choices": [string] (mcq only), "answerIndex": number (mcq only), "answer": number (numeric only), "tolerance": number (numeric only), "unit": string or null,
  "modelAnswer": string (short only), "keyPoints": [string] (short only), "explanation": string, "difficulty": 1|2|3,
  "quote": string or null, "docRef": "D0" or null, "page": number or null}}]}}

LEARNING OBJECTIVES
{obj_lines}

COURSE MATERIAL EXCERPTS
{exc}"""


def validate_question(raw, allowed_concepts, excerpts_by_doc=None):
    """→ (question dict, None) or (None, reason). never trust model output unchecked."""
    if not isinstance(raw, dict):
        return None, "not an object"
    qtype = raw.get("type")
    if qtype not in QUESTION_TYPES:
        return None, "unknown question type"
    prompt = raw.get("prompt")
    if not isinstance(prompt, str) or not 10 <= len(prompt.strip()) <= 1500:
        return None, "missing or overly long prompt"
    explanation = raw.get("explanation")
    if not isinstance(explanation, str) or not explanation.strip():
        return None, "missing explanation"
    if EXAM_CLAIM.search(prompt) or EXAM_CLAIM.search(explanation):
        return None, "claims to predict exam content"
    concept_ids = [c for c in (raw.get("conceptIds") or []) if c in allowed_concepts] if isinstance(raw.get("conceptIds"), list) else []
    if not concept_ids:
        return None, "not linked to a known concept"
    difficulty = raw.get("difficulty")
    difficulty = difficulty if isinstance(difficulty, int) and not isinstance(difficulty, bool) and 1 <= difficulty <= 3 else 2

    q = {"type": qtype, "conceptIds": list(dict.fromkeys(concept_ids)), "prompt": prompt.strip(),
         "explanation": explanation.strip()[:2000], "difficulty": difficulty}

    if qtype == "mcq":
        choices = raw.get("choices")
        if not isinstance(choices, list) or not 3 <= len(choices) <= 6:
            return None, "multiple choice needs 3–6 choices"
        clean = [c.strip()[:300] for c in choices if isinstance(c, str) and c.strip()]
        if len(clean) != len(choices) or len({c.lower() for c in clean}) != len(clean):
            return None, "choices must be distinct non-empty strings"
        idx = raw.get("answerIndex")
        if not isinstance(idx, int) or isinstance(idx, bool) or not 0 <= idx < len(clean):
            return None, "answerIndex out of range"
        q.update({"choices": clean, "answerIndex": idx})
    elif qtype == "numeric":
        try:
            answer = safe_eval(raw.get("answer"))
        except NumericParseError:
            return None, "numeric answer isn't a number"
        tol = raw.get("tolerance")
        if tol is None:
            tol = abs(answer) * 0.01
        if isinstance(tol, bool) or not isinstance(tol, (int, float)) or tol < 0:
            return None, "invalid tolerance"
        tol = float(tol)
        if answer != 0 and tol > abs(answer) * 0.2:
            return None, "tolerance too loose"
        unit = raw.get("unit") if isinstance(raw.get("unit"), str) else None
        q.update({"answer": answer, "tolerance": tol, "unit": (unit or "").strip()[:30] or None})
    else:
        model = raw.get("modelAnswer")
        if not isinstance(model, str) or not model.strip():
            return None, "short answer needs a model answer"
        points = [p.strip()[:300] for p in (raw.get("keyPoints") or []) if isinstance(p, str) and p.strip()][:6]
        q.update({"modelAnswer": model.strip()[:2000], "keyPoints": points})

    grounding, source = "generated", None
    quote, doc_ref = raw.get("quote"), raw.get("docRef")
    m = re.fullmatch(r"D(\d+)", str(doc_ref or "").strip())
    if excerpts_by_doc and isinstance(quote, str) and quote.strip() and m and int(m.group(1)) in excerpts_by_doc:
        doc = excerpts_by_doc[int(m.group(1))]
        page = locate_quote(quote, doc["pages"])
        if page is not None:
            grounding = "source"
            source = {"documentId": doc["id"], "filename": doc.get("filename"), "page": page, "quote": quote.strip()[:300]}
    q["grounding"] = grounding
    q["source"] = source
    return q, None


def fallback_questions(concepts):
    """deterministic self-check prompts used when question generation fails."""
    out = []
    for c in concepts:
        desc = c.get("description") or ""
        out.append({
            "type": "short", "conceptIds": [c["id"]], "difficulty": 1,
            "prompt": f"Without looking at your notes, explain “{c['name']}” in your own words and work through one example of it.",
            "modelAnswer": desc or "Compare your explanation with your course notes or textbook.",
            "keyPoints": [], "explanation": "This is a self-check prompt (the AI question generator was unavailable). "
                                            "Grade yourself honestly against your notes.",
            "grounding": "fallback", "source": None,
        })
    return out


def public_question(q, reveal=False):
    """strip answers unless the student already answered."""
    out = {k: q.get(k) for k in ("id", "type", "conceptIds", "prompt", "choices", "unit", "difficulty", "grounding", "status")}
    if reveal:
        for k in ("answerIndex", "answer", "tolerance", "modelAnswer", "keyPoints", "explanation", "source"):
            out[k] = q.get(k)
    return out


