"""
diagnostic practice — pure functions (no flask, no firestore, no network).

  concepts      suggested from confirmed objectives + course documents, then accepted
  questions     generated by the model, validated here before anyone sees them
  grading       multiple choice and numeric answers are checked deterministically
                (numeric answers are evaluated with a small safe expression parser,
                so "3/4", "0.75" and "sqrt(9)/4" all count); short answers are
                self-graded against a model answer — the model never grades
  mastery       transparent rules over recent attempts (below); confidence is
                tracked but never counts as evidence of knowing something
"""

import ast
import math
import re
from datetime import datetime, timedelta, timezone

